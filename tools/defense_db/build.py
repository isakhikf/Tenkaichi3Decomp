#!/usr/bin/env python3
"""UDE-DB1: audited JSON -> deterministic C tables + additive SQLite import.

Standard library only. Never reads or writes a running game. --check is read-only.
Existing SQLite tables/rows are preserved; only this import's owned rows change.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import sqlite3
import sys

ROOT = Path(__file__).resolve().parents[2]


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'))


def load(path):
    db = json.loads(path.read_text(encoding='utf-8-sig'))
    if db['meta']['versao'].split('.')[:2] != ['1', '1']:
        raise ValueError('Expected database v1.1')
    policy = db['ude_db1_policy']
    techniques = db['tecnicas']
    ids = [t['id'] for t in techniques]
    if len(ids) != 21 or len(set(ids)) != len(ids) or set(ids) != set(policy['techniques']):
        raise ValueError('Technique IDs differ from the policy contract')
    attacks = db['attack_records']
    if len(attacks) != 161 * 163:
        raise ValueError('Expected 161 x 163 attack records')
    keys = set()
    for r in attacks:
        key = (r['character_id'], r['attack_id'])
        if key in keys or not (0 <= key[0] < 161 and 0 <= key[1] < 163):
            raise ValueError('Duplicate/out-of-bounds attack key')
        keys.add(key)
        if not isinstance(r['flags'], int) or not 0 <= r['flags'] <= 0xffffffff:
            raise ValueError('Invalid attack flags')
        if any(not isinstance(r[k], int) or not 0 <= r[k] <= 4 for k in ('guard_a', 'guard_b', 'guard_c', 'guard_e')):
            raise ValueError('Invalid signed guard result')
        if not -128 <= r['priority'] <= 127:
            raise ValueError('Invalid signed attack priority')
        if not r.get('source') or not r.get('evidence'):
            raise ValueError('Attack without evidence')
    windows = db['janelas_de_defesa']['janelas']
    if [w['offset'] for w in windows] != [f'0x{x:04X}' for x in range(0x1068, 0x1084, 4)]:
        raise ValueError('Unexpected window offsets/order')
    for w, floor in zip(windows[:6], (-30, -30, -30, -15, -30, -30)):
        if w['regras_codigo']['floor'] != floor:
            raise ValueError('Native window floor changed: re-audit before generating')
    forbidden = {'VANISH_BEHIND', 'EMERGENCY_BLASTER_WAVE', 'ARMOR_REPEL', 'SKILL_DEFENSE', 'CLASH_MASH', 'CLASH_PROMPT', 'REFLECT_ABSORB', 'VANISHING_STEP', 'DRAGON_DASH_ESCAPE'}
    for name in forbidden:
        if policy['techniques'][name]['automatic']:
            raise ValueError('Forbidden automatic technique: ' + name)
    defaults = policy['defaults']
    if defaults['enabled'] != 0 or defaults['min_press_gap'] < 30 or defaults['recover'] != 0 or defaults['dragon_escape'] != 0:
        raise ValueError('Unsafe candidate defaults')
    return db


def render(db):
    sha = hashlib.sha256(canonical(db).encode()).hexdigest()
    p = db['ude_db1_policy']
    out = ['/* Do not edit. Generated by tools/defense_db/build.py from bt3_defesas_db.json.',
           f'   Canonical JSON SHA256: {sha} */', '#ifndef UDE_DB_TAB_H', '#define UDE_DB_TAB_H',
           f'#define UDE_DB_SOURCE_SHA256 "{sha}"',
           '#define UDE_DB_CHARACTER_COUNT 161', '#define UDE_DB_ATTACK_COUNT 163',
           '#define UDE_DB_ACTION_COUNT 0x13C',
           'static const UdeDbTechnique kUdeDbTechniques[UDE_DB_RECIPE_COUNT] = {',
           '    {"NONE", 0u, -1, 0, 0},']
    for t in db['tecnicas']:
        spec = p['techniques'][t['id']]
        out.append('    {%s, 0x%Xu, %d, %d, %d},' % (json.dumps(t['id']), spec['buttons'], spec['window'], spec['pulse'], spec['automatic']))
    out += ['};', 'static const UdeDbWindow kUdeDbWindows[6] = {']
    for w in db['janelas_de_defesa']['janelas'][:6]:
        r = w['regras_codigo']
        out.append('    {%d, %d, %d, %d}, /* %s */' % (r['floor'], r['input_condition'], r['requires_flag5'], r['early_press_sets_minus1'], w['offset']))
    out += ['};', 'static const UdeDbConfig kUdeDbDefaults = {']
    for key, value in p['defaults'].items():
        out.append(f'    .{key} = {value},')
    out += ['};', 'static const unsigned char kUdeDbPriority[] = {']
    ids = {t['id']: i+1 for i,t in enumerate(db['tecnicas'])}
    if len(set(p['priority'])) != len(p['priority']) or not set(p['priority']).issubset(ids):
        raise ValueError('Invalid policy priority list')
    out += ['    ' + ', '.join(str(ids[name]) for name in p['priority']), '};',
            'static const unsigned char kUdeDbThreatByAction[UDE_DB_ACTION_COUNT] = {']
    actions = [0] * 0x13c
    for segment in p['action_classes']:
        for action in range(segment['first'], segment['last'] + 1):
            if not 0 <= action < len(actions):
                raise ValueError('Invalid action range')
            actions[action] = segment['class']
    out.extend('    %d, /* 0x%03X */' % (value, action) for action, value in enumerate(actions))
    out += ['};', 'static const UdeDbAttack kUdeDbAttacks[UDE_DB_CHARACTER_COUNT][UDE_DB_ATTACK_COUNT] = {']
    records = sorted(db['attack_records'], key=lambda r: (r['character_id'], r['attack_id']))
    for ch in range(161):
        out.append(f'    {{ /* character {ch} */')
        for r in records[ch * 163:(ch + 1) * 163]:
            out.append('        {0x%08Xu, {%d,%d,%d,%d}, %d}, /* 0x%02X */' % (
                r['flags'], r['guard_a'], r['guard_b'], r['guard_c'], r['guard_e'], r['priority'], r['attack_id']))
        out.append('    },')
    out += ['};', '#endif', '']
    return '\n'.join(out), sha


SCHEMA = '''
CREATE TABLE IF NOT EXISTS technique(
 id TEXT PRIMARY KEY, owner TEXT NOT NULL, automatic INTEGER NOT NULL,
 confidence TEXT NOT NULL, data TEXT NOT NULL CHECK(json_valid(data)));
CREATE TABLE IF NOT EXISTS "window"(
 offset INTEGER PRIMARY KEY, owner TEXT NOT NULL, floor INTEGER,
 data TEXT NOT NULL CHECK(json_valid(data)));
CREATE TABLE IF NOT EXISTS threat_class(
 id INTEGER PRIMARY KEY, owner TEXT NOT NULL, name TEXT NOT NULL,
 data TEXT NOT NULL CHECK(json_valid(data)));
CREATE TABLE IF NOT EXISTS attack_record(
 character_id INTEGER NOT NULL, attack_id INTEGER NOT NULL, owner TEXT NOT NULL,
 flags INTEGER NOT NULL, guard_a INTEGER NOT NULL, guard_b INTEGER NOT NULL,
 guard_c INTEGER NOT NULL, guard_e INTEGER NOT NULL, priority INTEGER NOT NULL,
 data TEXT NOT NULL CHECK(json_valid(data)), PRIMARY KEY(character_id,attack_id));
CREATE TABLE IF NOT EXISTS evidence(
 owner TEXT NOT NULL, kind TEXT NOT NULL, item_key TEXT NOT NULL, field TEXT NOT NULL,
 status TEXT NOT NULL, confidence TEXT NOT NULL, data TEXT NOT NULL CHECK(json_valid(data)),
 PRIMARY KEY(owner,kind,item_key,field));
CREATE TABLE IF NOT EXISTS ude_db_import(
 owner TEXT PRIMARY KEY, version TEXT NOT NULL, json_sha256 TEXT NOT NULL);
'''
OWNER = 'UDE-DB1'


def merge_sqlite(path, db, sha):
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path)
    try:
        # Schema is additive. Reject incompatible pre-existing names instead of
        # dropping/recreating any table that may belong to another consumer.
        for table, required in {'technique': {'id','owner','automatic','confidence','data'},
                                'window': {'offset','owner','floor','data'},
                                'threat_class': {'id','owner','name','data'},
                                'attack_record': {'character_id','attack_id','owner','flags','guard_a','guard_b','guard_c','guard_e','priority','data'},
                                'evidence': {'owner','kind','item_key','field','status','confidence','data'}}.items():
            actual = {r[1] for r in connection.execute(f'PRAGMA table_info("{table}")')}
            if actual and not required.issubset(actual):
                raise ValueError('Incompatible existing SQLite table: ' + table)
        connection.executescript(SCHEMA)
        with connection:
            for table in ('technique', 'window', 'threat_class', 'attack_record', 'evidence'):
                connection.execute(f'DELETE FROM "{table}" WHERE owner=?', (OWNER,))
            for t in db['tecnicas']:
                connection.execute('INSERT INTO technique VALUES(?,?,?,?,?)', (t['id'], OWNER, db['ude_db1_policy']['techniques'][t['id']]['automatic'], t['confianca'], canonical(t)))
            for w in db['janelas_de_defesa']['janelas']:
                connection.execute('INSERT INTO "window" VALUES(?,?,?,?)', (int(w['offset'],16), OWNER, w.get('piso'), canonical(w)))
            for t in db['classes_de_ameaca']['classes']:
                connection.execute('INSERT INTO threat_class VALUES(?,?,?,?)', (t['id'], OWNER, t['nome'], canonical(t)))
            connection.executemany('INSERT INTO attack_record VALUES(?,?,?,?,?,?,?,?,?,?)',
                ((r['character_id'],r['attack_id'],OWNER,r['flags'],r['guard_a'],r['guard_b'],r['guard_c'],r['guard_e'],r['priority'],canonical(r)) for r in db['attack_records']))
            connection.executemany('INSERT INTO evidence VALUES(?,?,?,?,?,?,?)',
                ((OWNER,'audit',r['section'],r['field'],r['status'],r['confianca'],canonical(r)) for r in db['auditoria_campos']))
            connection.executemany('INSERT INTO evidence VALUES(?,?,?,?,?,?,?)',
                ((OWNER,'attack',f"{r['character_id']}:{r['attack_id']}",'record','ok',r['confidence'],canonical({'source':r['source'],'evidence':r['evidence']})) for r in db['attack_records']))
            connection.execute('INSERT INTO ude_db_import VALUES(?,?,?) ON CONFLICT(owner) DO UPDATE SET version=excluded.version,json_sha256=excluded.json_sha256',
                               (OWNER, db['meta']['versao'], sha))
        if connection.execute('PRAGMA integrity_check').fetchone()[0] != 'ok':
            raise ValueError('SQLite integrity check failed')
    finally:
        connection.close()


def check_sqlite(path, db, sha):
    c = sqlite3.connect(path.resolve().as_uri() + '?mode=ro&immutable=1', uri=True)
    try:
        assert c.execute('SELECT json_sha256 FROM ude_db_import WHERE owner=?',(OWNER,)).fetchone() == (sha,), 'stale SQLite import'
        for table, count in [('technique',21),('window',7),('threat_class',7),('attack_record',26243)]:
            assert c.execute(f'SELECT count(*) FROM "{table}" WHERE owner=?',(OWNER,)).fetchone()[0] == count, table
        for row in c.execute('SELECT character_id,attack_id,data FROM attack_record WHERE owner=? ORDER BY character_id,attack_id',(OWNER,)):
            record = db['attack_records'][row[0]*163 + row[1]]
            assert row[2] == canonical(record), f'attack content differs: {row[:2]}'
    finally:
        c.close()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--json', type=Path, default=ROOT/'bt3_defesas_db.json')
    p.add_argument('--header', type=Path, default=ROOT/'port/src/ude_db_tab.h')
    p.add_argument('--sqlite', type=Path, default=ROOT/'bt3_combat_database.sqlite')
    p.add_argument('--check', action='store_true')
    p.add_argument('--header-only', action='store_true')
    args = p.parse_args()
    db = load(args.json)
    text, sha = render(db)
    if args.check:
        if not args.header.is_file() or args.header.read_text(encoding='utf-8') != text:
            raise ValueError('JSON/header diverged; run python tools/defense_db/build.py')
        if not args.header_only:
            check_sqlite(args.sqlite, db, sha)
    else:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(text, encoding='utf-8', newline='\n')
        if not args.header_only:
            merge_sqlite(args.sqlite, db, sha)
    print(json.dumps({'mode':'check' if args.check else 'build', 'techniques':21,'windows':7,'attacks':26243,'json_sha256':sha,'sqlite':not args.header_only}))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, AssertionError, KeyError, sqlite3.Error) as exc:
        print('defense_db: ' + str(exc), file=sys.stderr)
        sys.exit(1)
